const toDataUrl = async (path: string): Promise<string> => {
  const response = await fetch(path);
  if (!response.ok) throw new Error(`Failed to load showcase asset: ${path}`);
  const blob = await response.blob();
  return new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => (typeof reader.result === 'string' ? resolve(reader.result) : reject(new Error('Invalid data URL')));
    reader.onerror = () => reject(new Error('FileReader failed'));
    reader.readAsDataURL(blob);
  });
};

